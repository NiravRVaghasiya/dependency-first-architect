"""REPORT.md from summary.json: deterministic markdown, so CI regenerates it and byte-compares.

    render_report(summary, manifest) -> str
    write_report(run_dir) -> str            <run>/summary.json + manifest.json -> <run>/REPORT.md
    check_report(run_dir) -> (ok, diff)     regenerate and compare with the committed REPORT.md

Every number comes from summary.json. The manifest supplies only names and descriptions (the
config's conditions and prompts, versions), never a statistic. The report describes differences
and their uncertainty; it ranks nothing and gives no p-values. It never contains the words
winner, best, beats or proves: the fixed text avoids them, and every string taken from the config
or the summary passes through `_quote`, which also removes them, so the rule holds whatever a
config (or a hand-edited summary) says.

Number formats: 1 decimal for rubric scores (/20, /44, /36, per-dimension) and trap counts,
2 decimals for 0-1 quantities (coverage, lint, AUC, accuracy, alpha, correlations, effect sizes,
efficiency ratios), integers for words and tokens, 2 decimals for USD; "n/a" for None.
"""

import difflib
import re

from . import records

HEADER = "<!-- GENERATED by eval/dfa_eval/report.py from summary.json — do not hand-edit -->"
RANKING_WORDS = re.compile(r"\b(?:winner|best|beats|proves)\b", re.I)

# Metrics in the condition and per-prompt tables, in column order: (metric, short label).
TABLE_METRICS = (
    ("adherence_total", "Adherence"), ("eq_total", "EQ"), ("eq_core", "EQ-core"),
    ("checklist_coverage", "Checklist coverage"), ("traps_present", "Traps present"),
    ("lint_score", "Lint"), ("words", "Words"), ("cost_usd", "Cost (USD)"),
)
METRIC_NAMES = {
    "adherence_total": "adherence", "eq_total": "EQ", "eq_core": "EQ-core",
    "checklist_coverage": "checklist coverage", "traps_present": "traps present",
    "lint_score": "lint", "words": "words", "eq_per_1k_tokens": "EQ per 1k tokens",
    "cost_usd": "cost (USD)",
}
TWO_DECIMALS = ("checklist_coverage", "lint_score", "cost_usd", "eq_per_1k_tokens",
                "adherence_per_1k_tokens")
INTEGERS = ("words", "visible_tokens_est", "output_tokens")

HOW_TO_READ = """## How to read this

- **Adherence** is methodology adherence: how closely a plan does what the Dependency-First
  Architect skill asks for, scored with the skill author's own rubric. It is not a quality
  score; plans written with the skill are expected to score high on it by construction.
- **EQ** (engineering quality) is an LLM judge's score of the written plan against a rubric
  authored without access to the skill. It judges plans, not outcomes: it does not show that a
  system built from the plan works. **EQ-core** leaves out the EQ dimensions that overlap the
  methodology.
- **Lint** is a deterministic check of the plan-template v2 format. It measures format
  adherence, not quality.
- The judges are language models from the same family as the generator (in some runs the same
  model; see the contrast notes), so they may share its idea of what a good plan contains.
- Intervals are 95%. The t-interval is computed across prompts, each prompt weighted equally;
  with few prompts it is wide. The bootstrap interval resamples prompts, then runs within each
  prompt. dz is the paired standardized difference across prompts. g (Hedges) divides the mean
  per-prompt difference by the pooled within-prompt SD (run-to-run spread), and Cliff's delta
  counts only pairs of plans for the same prompt, so prompt difficulty does not leak into either.
- This report gives no p-values and no rankings. It describes differences and their uncertainty."""


# --- formatting -----------------------------------------------------------------------------

def _quote(text):
    """Config text for a table cell or a line: one line, pipes escaped, no ranking words."""
    if text is None:
        return "n/a"
    text = " ".join(str(text).split()).replace("|", "\\|")
    return RANKING_WORDS.sub("[…]", text)


def _num(x, digits):
    if x is None:
        return "n/a"
    s = f"{x:.{digits}f}"
    return s[1:] if s.startswith("-") and float(s) == 0 else s


def _signed(x, digits):
    if x is None:
        return "n/a"
    s = f"{x:+.{digits}f}"
    return s[1:] if float(s) == 0 else s


def _digits(metric):
    if metric in INTEGERS:
        return 0
    if metric in TWO_DECIMALS:
        return 2
    return 1


def _interval(ci, digits):
    if not ci:
        return "n/a"
    return f"[{_num(ci[0], digits)}, {_num(ci[1], digits)}]"


def _mean_sd_ci(described, digits):
    if not described or described.get("mean") is None:
        return "n/a"
    interval = _interval(described["ci95"], digits) if described["ci95"] else "[n/a]"
    return f"{_num(described['mean'], digits)} ± {_num(described['sd'], digits)} {interval}"


def _mean_sd(described, digits):
    if not described or described.get("mean") is None:
        return "n/a"
    return f"{_num(described['mean'], digits)} ± {_num(described['sd'], digits)}"


def _usd(x):
    return "n/a" if x is None else f"${_num(x, 2)}"


def _table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return out


def metric_name(metric):
    """Display name of a contrast metric; eq_total@<judge> is EQ from that judge alone."""
    if metric.startswith("eq_total@"):
        return f"EQ, judge {metric.split('@', 1)[1]} only"
    return METRIC_NAMES.get(metric, _quote(metric))


def _label(summary, metric, short):
    scale = summary["metrics"][metric]["scale"]
    if scale.get("max") is not None and scale["max"] > 1:
        return f"{short} (/{_num(scale['max'], 0)})"
    return short


def _prompt_mean(condition_entry, metric):
    stat = condition_entry["metrics"].get(metric)
    return _num(stat["prompt_means"]["mean"], 2) if stat else "n/a"


# --- sections -------------------------------------------------------------------------------

def _what_was_run(summary, manifest):
    config = manifest.get("config", {})
    run = summary.get("run", {})
    cost = summary.get("cost", {})
    total = cost.get("total", {})
    rubrics = summary.get("generated_from", {}).get("rubrics", {})
    out = ["## What was run", ""]
    description = config.get("description")
    out.append(f"- **Benchmark:** {_quote(config.get('name'))}"
               + (f" — {_quote(description)}" if description else ""))
    window = ""
    if run.get("first_generation_started"):
        window = (f"; generations ran from {_quote(run['first_generation_started'])} to "
                  f"{_quote(run.get('last_generation_finished'))}")
    out.append(f"- **Run:** {_quote(summary['run_id'])}, created {_quote(manifest.get('created'))}"
               + window)
    out.append(f"- **Versions:** harness {_quote(manifest.get('harness_version'))}; skill "
               f"{_quote(manifest.get('skill', {}).get('version'))}; repo commit "
               f"{_quote(manifest.get('repo_commit'))}")
    prompts, conditions = config.get("prompts", []), config.get("conditions", {})
    judges = config.get("judges", [])
    per_rubric = "; ".join(
        f"{_quote(r)} by " + (", ".join(_quote(j["id"]) for j in judges
                                         if not j.get("rubrics") or r in j["rubrics"]) or "none")
        for r in rubrics) or "none"
    out.append(f"- **Design:** {len(prompts)} prompts × {len(conditions)} conditions × "
               f"{len(config.get('generators', []))} generator(s); "
               f"{config.get('runs_per_cell', 'n/a')} run(s) per cell; "
               f"{config.get('judge_repeats', 1)} repeat(s) per judge and rubric; rubrics: "
               + per_rubric)
    superseded = cost.get("superseded") or {}
    replaced = (f", superseded by a retry {_usd(superseded.get('cost_usd'))} over "
                f"{superseded['n_calls']} record(s)" if superseded.get("n_calls") else "")
    out.append(f"- **Total cost:** {_usd(total.get('cost_usd'))} over {total.get('n_calls', 0)} "
               f"records (generation {_usd(cost.get('generation', {}).get('cost_usd'))}, judging "
               f"{_usd(cost.get('judging', {}).get('cost_usd'))}, probes "
               f"{_usd(cost.get('probe', {}).get('cost_usd'))}{replaced}; a judgment retried "
               f"after an invalid reply is one record with the cost of every attempt); "
               f"{total.get('n_unknown_cost', 0)} record(s) with unknown cost are not included")

    out += ["", "### Models", ""]
    rows = []
    for role, entries in (("generator", run.get("generators", [])),
                          ("judge", run.get("judges", []))):
        for e in entries:
            rows.append([role, _quote(e["id"]), _quote(e["provider"]),
                         _quote(e.get("model_requested")), _quote(e.get("effort")),
                         ", ".join(_quote(m) for m in e.get("models_used", [])) or "n/a",
                         f"{e.get('n_ok', 0)} of {e.get('n_records', 0)}"])
    out += _table(["Role", "ID", "Provider", "Model requested", "Effort", "Models used",
                   "OK calls"], rows)
    probe_judges = run.get("probe_judges", [])
    out += ["", "Leakage probe judges: " + (", ".join(_quote(j) for j in probe_judges)
                                            or "none (probe disabled)") + "."]

    out += ["", "### Conditions", ""]
    rows = []
    for name, cond in conditions.items():
        skill = cond.get("skill_name") if cond.get("kind") == "skill" else None
        cap = cond.get("length_cap_words")
        rows.append([_quote(name), _quote(cond.get("kind")), _quote(skill) if skill else "—",
                     f"{cap} words" if cap else "—", _quote(cond.get("description"))])
    out += _table(["Condition", "Kind", "Skill", "Length cap", "Description"], rows)

    out += ["", "### Prompts", ""]
    out += _table(["Prompt", "Kind", "Title", "Request"],
                  [[_quote(p["id"]), _quote(p.get("kind")), _quote(p.get("title")),
                    _quote(p.get("request"))] for p in prompts])
    contrasts = config.get("contrasts", [])
    out += ["", "Contrasts (treatment − control): "
            + ("; ".join(f"{_quote(c['treatment'])} − {_quote(c['control'])}" for c in contrasts)
               or "none") + "."]
    return out


def _conditions(summary):
    metrics = [(m, _label(summary, m, short)) for m, short in TABLE_METRICS
               if m in summary["metrics"]]
    out = ["## Results by condition", "",
           "Each cell: mean of the per-prompt means ± SD across prompts [95% t-interval across "
           "prompts]. Plans counts ok generations.", ""]
    rows = []
    for entry in summary["conditions"]:
        row = [_quote(entry["condition"]), _quote(entry["generator"]), str(entry["n_prompts"]),
               str(entry["n_generations"])]
        row += [_mean_sd_ci(entry["metrics"][m]["prompt_means"], _digits(m)) for m, _ in metrics]
        rows.append(row)
    out += _table(["Condition", "Generator", "Prompts", "Plans"] + [label for _, label in metrics],
                  rows)
    return out


def _contrasts(summary):
    out = ["## Contrasts", "",
           "Mean difference (treatment − control) of per-prompt cell means, with its 95% "
           "t-interval across prompts and the 95% cluster-bootstrap interval. n = prompts with "
           "both arms (generations in treatment / control).", ""]
    if not summary["contrasts"]:
        return out + ["No contrasts were configured, or no generator ran both arms of one."]
    rows = []
    for c in summary["contrasts"]:
        digits = _digits(c["metric"])
        rows.append([
            f"{_quote(c['treatment'])} − {_quote(c['control'])}", _quote(c["generator"]),
            metric_name(c["metric"]),
            _signed(c["mean_diff"], digits), _interval(c["diff"]["ci95"], digits),
            _interval(c["cluster_bootstrap_ci"], digits),
            _num(c["dz"], 2), _num(c["hedges_g"], 2), _num(c["cliffs_delta"], 2),
            f"{c['n_prompts']} ({c['n_treatment']} / {c['n_control']})",
            "; ".join(_quote(n) for n in c["notes"]) or "—",
        ])
    out += _table(["Contrast", "Generator", "Metric", "Mean diff", "t-CI", "Bootstrap CI", "dz",
                   "g", "Cliff's δ", "n", "Notes"], rows)
    return out


def _length(summary):
    out = ["## Length and efficiency", "",
           "Descriptive only. Efficiency columns are means of per-prompt means; the Spearman "
           "correlations are over generations. Within cap: share of plans at most 10% over the "
           "length cap.", ""]
    by_condition = {(c["condition"], c["generator"]): c for c in summary["conditions"]}
    rows = []
    for entry in summary["length"]:
        cond = by_condition.get((entry["condition"], entry["generator"]), {"metrics": {}})
        cap = entry.get("length_cap_words")
        rows.append([
            _quote(entry["condition"]), _quote(entry["generator"]), str(entry["n"]),
            _mean_sd(entry["words"], 0), _prompt_mean(cond, "eq_per_1k_tokens"),
            _prompt_mean(cond, "adherence_per_1k_tokens"),
            _num(entry.get("spearman_words_eq_total"), 2),
            _num(entry.get("spearman_words_adherence_total"), 2),
            str(cap) if cap else "—",
            (f"{_num(entry['cap_compliance'], 2)} ({entry['within_cap']} of {entry['n']})"
             if cap else "—"),
        ])
    out += _table(["Condition", "Generator", "Plans", "Words (mean ± sd)", "EQ per 1k tokens",
                   "Adherence per 1k tokens", "Spearman(words, EQ)",
                   "Spearman(words, adherence)", "Cap (words)", "Within cap"], rows)
    return out


def _reliability(summary):
    out = ["## Judge reliability", "",
           "Krippendorff's alpha (interval metric) over generation totals measures absolute "
           "agreement; coders are (judge, repeat) pairs. Mean abs. difference: mean |total "
           "difference| over every pair of coders that scored the same plan. Rank consistency: "
           "Spearman correlation of two coders' totals over the plans both scored, with the mean "
           "offset (second minus first), so a judge that scores everything higher but in the same "
           "order shows up as an offset, not as disagreement.", ""]
    if not summary["judge_reliability"]:
        return out + ["No rubric was summarized."]
    rows = []
    for entry in summary["judge_reliability"]:
        per_judge = "; ".join(f"{_quote(j['judge'])} {_num(j['mean_total'], 1)} (n={j['n']})"
                              for j in entry["per_judge"]) or "n/a"
        consistency = "; ".join(
            f"{_quote(c['coders'][0])} vs {_quote(c['coders'][1])}: ρ {_num(c['spearman'], 2)}, "
            f"offset {_num(c['mean_offset'], 1)} (n={c['n']})"
            for c in entry.get("rank_consistency", [])) or "n/a"
        rows.append([_quote(entry["rubric"]), str(entry["n_coders"]), str(entry["n_units"]),
                     _num(entry["alpha_interval"], 2), _num(entry["mean_abs_diff"], 1),
                     consistency, per_judge])
    out += _table(["Rubric", "Coders", "Units", "Alpha", "Mean abs. difference",
                   "Rank consistency", "Per-judge mean total"], rows)
    return out


def _leakage(summary):
    out = ["## Leakage probe", ""]
    if not summary["leakage"]:
        return out + ["No probe was run."]
    out += [_quote(summary["leakage"][0].get("note", "")), ""]
    rows = []
    for entry in summary["leakage"]:
        comparisons = [("skill conditions vs plain conditions", entry["skill_vs_plain"])]
        comparisons += [(f"{_quote(c['treatment'])} vs {_quote(c['control'])}", c)
                        for c in entry["contrasts"]]
        for name, d in comparisons:
            accuracy = "n/a" if d["accuracy"] is None else (
                f"{_num(d['accuracy'], 2)} {_interval(d['accuracy_ci95'], 2)}")
            rows.append([_quote(entry["judge"]), _quote(entry.get("generator", "—")), name,
                         f"{d['n']} ({d['n_positive']} / {d['n_negative']})",
                         _num(d["auc"], 2), accuracy])
    out += _table(["Probe judge", "Generator", "Comparison", "n (positive / negative)", "AUC",
                   "Accuracy at 0.5 [Wilson 95% CI]"], rows)
    return out


def _cells(summary):
    metrics = [(m, _label(summary, m, short)) for m, short in TABLE_METRICS
               if m in summary["metrics"]]
    out = ["## Per-prompt cells", "", "Each cell: mean ± SD over the cell's runs.", ""]
    rows = []
    for cell in summary["cells"]:
        row = [_quote(cell["prompt"]), _quote(cell["condition"]), _quote(cell["generator"]),
               str(cell["n_generations"]), str(cell["n_failed"])]
        row += [_mean_sd(cell["metrics"][m], _digits(m)) for m, _ in metrics]
        rows.append(row)
    out += _table(["Prompt", "Condition", "Generator", "Plans", "Failed"]
                  + [label for _, label in metrics], rows)
    return out


def _flags(summary):
    out = ["## Flags", ""]
    return out + ([f"- {_quote(flag)}" for flag in summary["flags"]] or ["None."])


# --- entry points ---------------------------------------------------------------------------

def render_report(summary, manifest):
    """REPORT.md text for a summary (numbers) and its run's manifest (names, descriptions)."""
    out = [HEADER, "", f"# Evaluation report: {_quote(summary['run_id'])}", ""]
    for section in (_what_was_run(summary, manifest), HOW_TO_READ.split("\n"),
                    _conditions(summary), _contrasts(summary), _length(summary),
                    _reliability(summary), _leakage(summary), _cells(summary), _flags(summary)):
        out += section + [""]
    return "\n".join(out).rstrip("\n") + "\n"


def _inputs(run_dir):
    run = records.RunDir(run_dir)
    return run, records.read_json(run.summary_path), run.manifest()


def write_report(run_dir):
    """Write <run>/REPORT.md from <run>/summary.json and manifest.json; return the text."""
    run, summary, manifest = _inputs(run_dir)
    text = render_report(summary, manifest)
    records.write_text(run.report_path, text)
    return text


def check_report(run_dir):
    """(ok, diff): regenerate REPORT.md from summary.json and compare with the committed file."""
    run = records.RunDir(run_dir)
    if not run.summary_path.exists():
        return False, f"{records.SUMMARY} is missing; run `python eval/run.py aggregate` first\n"
    _, summary, manifest = _inputs(run_dir)
    expected = render_report(summary, manifest)
    if not run.report_path.exists():
        return False, f"{records.REPORT} is missing; run `python eval/run.py report`\n"
    current = run.report_path.read_bytes().decode("utf-8").replace("\r\n", "\n")
    if current == expected:
        return True, ""
    return False, "".join(difflib.unified_diff(
        current.splitlines(True), expected.splitlines(True),
        fromfile=f"{records.REPORT} (committed)", tofile=f"{records.REPORT} (regenerated)"))
