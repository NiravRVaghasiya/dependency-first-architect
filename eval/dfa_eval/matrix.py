"""docs/evaluation-matrix.md: the agents the skill supports and what has been measured with each.

    render_matrix(repo_root) -> str
    write_matrix(repo_root) -> str          writes docs/evaluation-matrix.md
    check_matrix(repo_root) -> (ok, diff)   regenerate and compare with the committed file

Generated from eval/agents.json (the declared install artifacts), every committed run
(eval/results/<run>/manifest.json + summary.json) and the v1.0.0 pilot recorded in
examples/scoring/generation.json + judgments.json. A status is computed from that evidence,
never declared:

- Supported: an install artifact exists in this repo. Nothing has been measured.
- Tested: at least one committed run produced plans with this agent + model.
- Experimentally evaluated: a committed run with >= 5 prompts, >= 3 runs per (prompt, condition)
  cell for a skill condition and a control, blinded judging by >= 1 judge model different from
  the generator, and a summary with confidence intervals.

How the rules are read: the skill condition is a condition running the dependency-first-architect
skill, and the control is the control of a configured contrast with it; the >= 5 prompts must
each have >= 3 ok plans in both cells; the judge model must be named and differ from the
generator's requested model; and that contrast's summary entry for adherence or EQ must have a
t-interval. The pilot has no summary.json, 1 run per arm and judges on the generator's own
model, so it can only be Tested.

Rows: one per (committed run, generator); one for the pilot; and, for each agent in agents.json
with no committed run at the current skill version (VERSION), a "Supported" row with Runs 0.
Runs counts ok plans. Agent: "Claude Code" for claude-cli generators, otherwise the generator's
options.agent (declared in the run's config), otherwise its provider name.
"""

import difflib
import statistics
from collections import Counter
from pathlib import Path

from . import records, schema, schemas, stats

HEADER = ("<!-- GENERATED by eval/dfa_eval/matrix.py from eval/agents.json, eval/results/ and "
          "examples/scoring/ — do not hand-edit -->")
MATRIX = Path("docs") / "evaluation-matrix.md"
DFA_SKILL = "dependency-first-architect"
MIN_PROMPTS = 5
MIN_RUNS = 3
SUPPORTED, TESTED, EVALUATED = "Supported", "Tested", "Experimentally evaluated"
PILOT_SKILL_VERSION = "1.0.0"
AGENT_KEYS = ("agent", "artifact", "install", "notes")

STATUS_DEFINITIONS = f"""## Status definitions

- **{SUPPORTED}**: an install artifact exists in this repo. Nothing has been measured.
- **{TESTED}**: at least one committed run produced plans with this agent + model.
- **{EVALUATED}**: a committed run with ≥ {MIN_PROMPTS} prompts, ≥ {MIN_RUNS} runs per
  (prompt, condition) cell for a skill condition and a control, blinded judging by ≥ 1 judge
  model different from the generator, a summary with confidence intervals, and skill plans that
  could read the skill's files.

Statuses are computed from the committed evidence by `eval/dfa_eval/matrix.py`; none is declared
by hand."""

MATRIX_NOTE = """\
Runs counts the plans a row's evidence produced. Measured result quotes mean differences
(treatment − control) with 95% t-intervals across prompts from the run's summary.json: adherence
is methodology adherence, scored with the skill author's own rubric, so a high value for plans
written with the skill is expected by construction; EQ is an LLM judge's engineering-quality score
of the written plan, not of outcomes. Read each run's REPORT.md for the caveats."""


def _cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def _num(x, digits=1):
    if x is None:
        return "n/a"
    s = f"{x:.{digits}f}"
    return s[1:] if s.startswith("-") and float(s) == 0 else s


def _signed(x, digits=1):
    if x is None:
        return "n/a"
    s = f"{x:+.{digits}f}"
    return s[1:] if float(s) == 0 else s


def _interval(ci, digits=1):
    return "n/a" if not ci else f"[{_num(ci[0], digits)}, {_num(ci[1], digits)}]"


# --- inputs ---------------------------------------------------------------------------------

def load_agents(repo_root):
    """eval/agents.json, checked: a list of {agent, artifact, install, notes} with unique agents."""
    path = Path(repo_root) / "eval" / "agents.json"
    agents = records.read_json(path)
    if not isinstance(agents, list):
        raise ValueError(f"{path}: expected a list of agents")
    seen = set()
    for i, entry in enumerate(agents):
        if not isinstance(entry, dict) or sorted(entry) != sorted(AGENT_KEYS) or not all(
                isinstance(entry[k], str) and entry[k].strip() for k in AGENT_KEYS):
            raise ValueError(f"{path}: entry {i} must have exactly the non-empty string fields "
                             + ", ".join(AGENT_KEYS))
        if entry["agent"] in seen:
            raise ValueError(f"{path}: agent {entry['agent']!r} is listed twice")
        seen.add(entry["agent"])
    return agents


def current_version(repo_root):
    path = Path(repo_root) / "VERSION"
    return path.read_text(encoding="utf-8").strip() if path.is_file() else "unknown"


def agent_name(generator):
    """The agent a config generator stands for."""
    if generator.get("provider") == "claude-cli":
        return "Claude Code"
    options = generator.get("options") or {}
    return options.get("agent") or generator.get("provider") or "unknown"


def classify(facts):
    """Status from facts: plans (ok plans), blinded, independent_judge, and contrasts, a list of
    {"paired_prompts": prompts with >= MIN_RUNS ok plans in both cells, "has_ci": bool}."""
    if not facts["plans"]:
        return SUPPORTED
    evaluated = (facts["blinded"] and facts["independent_judge"]
                 and facts.get("treatment_intact", True)
                 and any(c["paired_prompts"] >= MIN_PROMPTS and c["has_ci"]
                         for c in facts["contrasts"]))
    return EVALUATED if evaluated else TESTED


def _dfa_conditions(config, uncapped=False):
    return [c for c, v in config.get("conditions", {}).items()
            if v.get("kind") == "skill" and v.get("skill_name") == DFA_SKILL
            and not (uncapped and v.get("length_cap_words"))]


def _cell_counts(run_dir, summary):
    """(prompt, condition, generator) -> ok plans, from summary.json or else the records."""
    if summary:
        return {(c["prompt"], c["condition"], c["generator"]): c["n_generations"]
                for c in summary.get("cells", [])}
    counts = Counter()
    for gen in records.RunDir(run_dir).generations():
        if gen.get("status") == "ok":
            counts[(gen["prompt_id"], gen["condition"], gen["generator"])] += 1
    return dict(counts)


def run_facts(run_dir, manifest, summary, generator):
    """The status facts of one generator in one committed run."""
    config = manifest["config"]
    gid = generator["id"]
    counts = _cell_counts(run_dir, summary)
    prompts = [p["id"] for p in config.get("prompts", [])]
    contrasts = []
    for ct in config.get("contrasts", []):
        t, c = ct["treatment"], ct["control"]
        if t not in _dfa_conditions(config):
            continue
        paired = sum(1 for p in prompts if counts.get((p, t, gid), 0) >= MIN_RUNS
                     and counts.get((p, c, gid), 0) >= MIN_RUNS)
        has_ci = bool(summary) and any(
            e.get("treatment") == t and e.get("control") == c and e.get("generator") == gid
            and e.get("metric") in ("adherence_total", "eq_total")
            and (e.get("diff") or {}).get("ci95") is not None
            for e in summary.get("contrasts", []))
        contrasts.append({"treatment": t, "control": c, "paired_prompts": paired,
                          "has_ci": has_ci})
    judges = (summary or {}).get("run", {}).get("judges", [])
    model = generator.get("model")
    origin = (summary or {}).get("generated_from", {})
    return {
        "plans": sum(n for (p, c, g), n in counts.items() if g == gid),
        "blinded": bool(summary) and origin.get("blind_key_entries", 0) > 0
        and origin.get("judgments_used", 0) > 0,
        # A judge counts only through judgments the summary actually used (n_used).
        "independent_judge": bool(model) and any(
            j.get("n_used", j.get("n_ok", 0)) > 0 and j.get("model_requested")
            and j["model_requested"] != model for j in judges),
        "contrasts": contrasts,
        # A skill arm whose plans could not read the skill's files did not test the skill.
        "treatment_intact": not any(f"generator {gid}:" in flag
                                    and "could not read the skill's files" in flag
                                    for flag in (summary or {}).get("flags", [])),
    }


def _measured(config, summary, gid):
    """'dfa − baseline: adherence +x [lo, hi]; EQ +y [lo, hi] (t-CI over n prompts)' or '—'."""
    if not summary:
        return "—"
    conditions = config.get("conditions", {})
    plain = [c for c, v in conditions.items()
             if v.get("kind") == "plain" and not v.get("length_cap_words")]
    pairs = [(ct["treatment"], ct["control"]) for ct in config.get("contrasts", [])
             if ct["treatment"] in _dfa_conditions(config, uncapped=True)
             and ct["control"] in plain]
    if not pairs:  # a run of length-capped arms only: quote them, labeled by their names
        pairs = [(ct["treatment"], ct["control"]) for ct in config.get("contrasts", [])
                 if ct["treatment"] in _dfa_conditions(config)
                 and conditions.get(ct["control"], {}).get("kind") == "plain"
                 and conditions[ct["treatment"]].get("length_cap_words")
                 and conditions[ct["control"]].get("length_cap_words")]
    if not pairs:
        return "—"
    # dfa − baseline first; otherwise the first contrast this generator actually has results for
    # (a generator may run only some conditions).
    pairs.sort(key=lambda pair: pair != ("dfa", "baseline"))
    measured = {(e.get("treatment"), e.get("control")) for e in summary.get("contrasts", [])
                if e.get("generator") == gid and e.get("mean_diff") is not None}
    t, c = next((pair for pair in pairs if pair in measured), pairs[0])
    entries = {e["metric"]: e for e in summary.get("contrasts", [])
               if e.get("treatment") == t and e.get("control") == c and e.get("generator") == gid}
    parts, ns = [], []
    for metric, label in (("adherence_total", "adherence"), ("eq_total", "EQ")):
        e = entries.get(metric)
        if e and e.get("mean_diff") is not None:
            parts.append(f"{label} {_signed(e['mean_diff'])} {_interval(e['diff']['ci95'])}")
            ns.append(e.get("n_prompts"))
    if not parts:
        return "—"
    if len(set(ns)) == 1:
        return f"{t} − {c}: " + "; ".join(parts) + f" (t-CI over {ns[0]} prompts)"
    # The metrics cover different prompt counts: say which is which.
    parts = [f"{p} ({n} prompts)" for p, n in zip(parts, ns)]
    return f"{t} − {c}: " + "; ".join(parts) + " (t-CIs over prompts)"


def run_rows(repo_root):
    """Rows for every generator of every committed run under eval/results/, by run id."""
    results = Path(repo_root) / "eval" / "results"
    rows = []
    if not results.is_dir():
        return rows
    for run_dir in sorted((p for p in results.iterdir() if (p / records.MANIFEST).is_file()),
                          key=lambda p: p.name):
        manifest = schema.check(records.read_json(run_dir / records.MANIFEST), schemas.MANIFEST,
                                f"eval/results/{run_dir.name}/{records.MANIFEST}")
        summary_path = run_dir / records.SUMMARY
        summary = records.read_json(summary_path) if summary_path.is_file() else None
        config = manifest["config"]
        report = (run_dir / records.REPORT).is_file()
        for generator in config.get("generators", []):
            facts = run_facts(run_dir, manifest, summary, generator)
            model = generator.get("model") or "unknown"
            if generator.get("effort"):
                model += f" (effort {generator['effort']})"
            name = f"{config.get('name', 'run')} run {manifest['run_id']}"
            link = (f"[{name}](../eval/results/{run_dir.name}/{records.REPORT})" if report
                    else name)
            judges = sorted({j.get("model") or j["id"] for j in config.get("judges", [])})
            configuration = (f"{link}: {len(config.get('prompts', []))} prompts; conditions "
                             f"{', '.join(config.get('conditions', {}))}; "
                             f"{config.get('runs_per_cell')} "
                             f"run{'' if config.get('runs_per_cell') == 1 else 's'} per cell; judges "
                             f"{', '.join(judges) or 'none'}")
            rows.append({"agent": agent_name(generator), "model": model,
                         "skill_version": manifest["skill"]["version"],
                         "configuration": configuration, "runs": facts["plans"],
                         "status": classify(facts),
                         "measured": _measured(config, summary, generator["id"])})
    return rows


def pilot_row(repo_root):
    """The v1.0.0 pilot (examples/scoring), or None if its records are not in this tree."""
    scoring = Path(repo_root) / "examples" / "scoring"
    gen_path, judgments_path = scoring / "generation.json", scoring / "judgments.json"
    if not (gen_path.is_file() and judgments_path.is_file()):
        return None
    generation = records.read_json(gen_path)
    judgments = records.read_json(judgments_path)
    runs = generation["runs"]
    prompts = sorted({r["prompt"] for r in runs})
    per_cell = Counter((r["prompt"], r["arm"]) for r in runs)
    runs_per_arm = min(per_cell.values()) if per_cell else 0
    # Totals exactly as examples/scoring/tally.py: per-dimension median of the judges, summed.
    totals = {(p["prompt"], p["arm"]): sum(statistics.median(column) for column in
                                           zip(*(j["scores"] for j in p["judges"])))
              for p in judgments["plans"]}
    diffs = [totals[(p, "with")] - totals[(p, "without")] for p in prompts
             if (p, "with") in totals and (p, "without") in totals]
    described = stats.describe(diffs)
    same_model = generation["model"] in judgments.get("model", "")
    n_judges = judgments.get("judges_per_plan")
    paired = sum(1 for p in prompts if per_cell[(p, "with")] >= MIN_RUNS
                 and per_cell[(p, "without")] >= MIN_RUNS)
    facts = {"plans": len(runs), "blinded": True, "independent_judge": not same_model,
             "contrasts": [{"paired_prompts": paired, "has_ci": False}]}  # no summary.json
    judge_text = f"{n_judges} judges" + (" on the generator's own model" if same_model else "")
    return {
        "agent": "Claude Code",
        "model": f"{generation['model']} (effort {generation['effort']})",
        "skill_version": f"{PILOT_SKILL_VERSION} (commit {generation['skill']})",
        "configuration": (f"[v1.0.0 pilot](../examples/SCORECARD.md): with vs without the skill; "
                          f"{len(prompts)} prompts; {runs_per_arm} run per arm; {judge_text}"),
        "runs": len(runs), "status": classify(facts),
        "measured": (f"with − without: adherence (v1 rubric) {_signed(described['mean'])} "
                     f"{_interval(described['ci95'])} (t-CI over {described['n']} prompts); "
                     "EQ not measured"),
    }


def matrix_rows(repo_root):
    agents = load_agents(repo_root)
    version = current_version(repo_root)
    measured = run_rows(repo_root)
    pilot = pilot_row(repo_root)
    if pilot:
        measured.append(pilot)
    rows = []
    for entry in agents:
        mine = [r for r in measured if r["agent"] == entry["agent"]]
        if not any(r["skill_version"] == version for r in mine):
            rows.append({"agent": entry["agent"], "model": "—", "skill_version": version,
                         "configuration": f"install artifact `{entry['artifact']}`; "
                                          "no committed run at this version",
                         "runs": 0, "status": SUPPORTED, "measured": "—"})
        rows += mine
    declared = {entry["agent"] for entry in agents}
    rows += sorted((r for r in measured if r["agent"] not in declared),
                   key=lambda r: (r["agent"], r["skill_version"], r["configuration"]))
    return rows, agents, version


# --- entry points ---------------------------------------------------------------------------

def render_matrix(repo_root):
    rows, agents, version = matrix_rows(repo_root)
    out = [HEADER, "", "# Evaluation matrix", "",
           "Which agents the skill supports, and what has been measured with each.", "",
           STATUS_DEFINITIONS, "", "## Matrix", "",
           "| Agent | Model | Skill version | Configuration | Runs | Status | Measured result |",
           "|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append("| " + " | ".join(_cell(r[k]) for k in (
            "agent", "model", "skill_version", "configuration", "runs", "status", "measured"))
                   + " |")
    out += ["", MATRIX_NOTE, "", f"## Install artifacts (skill version {_cell(version)})", "",
            "| Agent | Artifact | Install | Notes |", "|---|---|---|---|"]
    for entry in agents:
        out.append(f"| {_cell(entry['agent'])} | `{_cell(entry['artifact'])}` | "
                   f"`{_cell(entry['install'])}` | {_cell(entry['notes'])} |")
    return "\n".join(out) + "\n"


def write_matrix(repo_root):
    text = render_matrix(repo_root)
    records.write_text(Path(repo_root) / MATRIX, text)
    return text


def check_matrix(repo_root):
    """(ok, diff): regenerate the matrix and compare with docs/evaluation-matrix.md."""
    path = Path(repo_root) / MATRIX
    expected = render_matrix(repo_root)
    if not path.is_file():
        return False, f"{MATRIX.as_posix()} is missing; run `python eval/run.py matrix`\n"
    current = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
    if current == expected:
        return True, ""
    return False, "".join(difflib.unified_diff(
        current.splitlines(True), expected.splitlines(True),
        fromfile=f"{MATRIX.as_posix()} (committed)", tofile=f"{MATRIX.as_posix()} (generated)"))
